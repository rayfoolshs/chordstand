#!/usr/bin/env node
/**
 * Generates THIRD_PARTY_NOTICES.md from the production dependency tree.
 *
 * Run after `npm install` or when dependencies change:
 *
 *   npm run notices
 *
 * The script uses `license-checker` to list every production dependency and
 * its declared license, then copies the matching license text. MIT and Apache
 * licenses require the notice to ship with the app, so this file is committed
 * and served with the app.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { execSync } from 'node:child_process'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const raw = execSync('npx --yes license-checker --production --json', {
  cwd: root,
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'ignore'],
})
const packages = JSON.parse(raw)

const own = 'chordstand@0.1.0'
const entries = Object.entries(packages)
  .filter(([name]) => name !== own)
  .sort(([a], [b]) => a.localeCompare(b))

const lines = []
lines.push('# Third-party notices')
lines.push('')
lines.push('Chordstand is a static web app. It bundles the following open-source')
lines.push('packages. MIT and Apache-2.0 licenses require their copyright notices to')
lines.push('ship with the app, so this file is included in the build and published with')
lines.push('the site.')
lines.push('')
lines.push('Generated by `npm run notices` from the production dependency tree.')
lines.push('')

for (const [name, info] of entries) {
  const license = info.licenses || 'UNKNOWN'
  lines.push(`## ${name}`)
  lines.push('')
  lines.push(`- License: ${license}`)
  if (info.repository) lines.push(`- Repository: ${info.repository}`)
  if (info.publisher) lines.push(`- Publisher: ${info.publisher}`)
  lines.push('')
  if (info.licenseFile) {
    try {
      const text = readFileSync(info.licenseFile, 'utf8').trim()
      lines.push('```text')
      lines.push(text)
      lines.push('```')
    } catch {
      lines.push('_License text not found in the package._')
    }
  } else {
    lines.push('_No license file found in the package._')
  }
  lines.push('')
}

writeFileSync(resolve(root, 'THIRD_PARTY_NOTICES.md'), lines.join('\n'), 'utf8')
// Also ship the notices with the app so the built site serves them.
writeFileSync(resolve(root, 'public/THIRD_PARTY_NOTICES.md'), lines.join('\n'), 'utf8')
console.log(`Wrote THIRD_PARTY_NOTICES.md (${entries.length} packages)`)
console.log('Also copied to public/THIRD_PARTY_NOTICES.md')
